"""Tests for provenance-checked MCCE input staging."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pytest

from nyl12_covalent.mcce_preparation import prepare_input
from scripts.prepare_mcce_input import main


def _atom_line(
    serial: int,
    atom_name: str,
    residue_name: str,
    chain: str,
    residue_number: int,
    coordinates: tuple[float, float, float],
    element: str,
    altloc: str = " ",
    insertion: str = " ",
) -> str:
    atom_field = f"{atom_name:>4s}"
    x, y, z = coordinates
    return (
        f"ATOM  {serial:5d} {atom_field}{altloc}{residue_name:3s} {chain}"
        f"{residue_number:4d}{insertion}   {x:8.3f}{y:8.3f}{z:8.3f}"
        f"  1.00  0.00          {element:>2s}\n"
    )


def _source(tmp_path: Path, *, duplicate: bool = False, altloc: str = " ") -> Path:
    records = [
        _atom_line(1, "N", "ALA", "A", 1, (1.0, 2.0, 3.0), "N", altloc),
        _atom_line(2, "CA", "ALA", "A", 1, (1.1, 2.1, 3.1), "C"),
        _atom_line(3, "CABC", "ALA", "A", 1, (1.2, 2.2, 3.2), "C"),
        _atom_line(4, "C", "GLY", "A", 2, (2.0, 3.0, 4.0), "C"),
        _atom_line(5, "O", "GLY", "A", 2, (2.1, 3.1, 4.1), "O"),
        _atom_line(6, "OXT", "GLY", "A", 2, (2.2, 3.2, 4.2), "O"),
    ]
    if duplicate:
        records.append(records[0])
    path = tmp_path / "source.pdb"
    path.write_text("".join(records) + "TER\nEND\n")
    return path


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def test_normalization_preserves_atoms_coordinates_oxt_and_four_char_names(
    tmp_path: Path,
) -> None:
    source = _source(tmp_path)
    original = source.read_bytes()
    output = tmp_path / "prepared"

    report = prepare_input(source, output, _digest(source), {"A": {"n": 1, "c": 2}})

    prepared = (output / "protein.pdb").read_bytes()
    before_atoms = [line for line in original.splitlines() if line.startswith(b"ATOM")]
    after_atoms = [line for line in prepared.splitlines() if line.startswith(b"ATOM")]
    assert (output / "original.pdb").read_bytes() == original
    assert [line[30:54] for line in before_atoms] == [
        line[30:54] for line in after_atoms
    ]
    assert [line[17:30] + line[54:] for line in before_atoms] == [
        line[17:30] + line[54:] for line in after_atoms
    ]
    assert [line[12:16] for line in after_atoms] == [
        b" N  ",
        b" CA ",
        b"CABC",
        b" C  ",
        b" O  ",
        b" OXT",
    ]
    assert prepared.endswith(b"TER\nEND\n")
    assert report["atom_count"] == 6
    assert report["coordinates_unchanged"] and report["oxt_records_preserved"]
    assert json.loads((output / "normalization.json").read_text()) == report


def test_preserves_and_audits_benign_pdb_metadata(tmp_path: Path) -> None:
    source = _source(tmp_path)
    metadata = (
        b"HEADER    TEST PDB\n"
        b"TITLE     REPAIRED PROTEIN\n"
        b"REMARK   1 GENERATED BY PDBFIXER\n"
        b"SEQRES   1 A    2  ALA GLY\n"
        b"CRYST1   10.000   10.000   10.000  90.00  90.00  90.00 P 1           1\n"
    )
    source.write_bytes(metadata + source.read_bytes())
    output = tmp_path / "prepared-metadata"

    report = prepare_input(source, output, _digest(source), {"A": {"n": 1, "c": 2}})

    prepared = (output / "protein.pdb").read_bytes()
    assert prepared.startswith(metadata)
    assert report["metadata_records_preserved"] == {
        "HEADER": {
            "count": 1,
            "sha256": hashlib.sha256(b"HEADER    TEST PDB\n").hexdigest(),
        },
        "TITLE": {
            "count": 1,
            "sha256": hashlib.sha256(b"TITLE     REPAIRED PROTEIN\n").hexdigest(),
        },
        "REMARK": {
            "count": 1,
            "sha256": hashlib.sha256(b"REMARK   1 GENERATED BY PDBFIXER\n").hexdigest(),
        },
        "SEQRES": {
            "count": 1,
            "sha256": hashlib.sha256(b"SEQRES   1 A    2  ALA GLY\n").hexdigest(),
        },
        "CRYST1": {
            "count": 1,
            "sha256": hashlib.sha256(
                b"CRYST1   10.000   10.000   10.000  90.00  90.00  90.00 P 1           1\n"
            ).hexdigest(),
        },
    }


@pytest.mark.parametrize(
    ("kwargs", "message"),
    [
        ({"expected_sha256": "0" * 64}, "SHA-256 mismatch"),
        ({"expected_termini": {"A": {"n": 1, "c": 3}}}, "Observed termini"),
    ],
)
def test_rejects_source_hash_or_termini_mismatch(
    tmp_path: Path, kwargs: dict[str, object], message: str
) -> None:
    source = _source(tmp_path)
    digest = str(kwargs.get("expected_sha256", _digest(source)))
    termini = kwargs.get("expected_termini", {"A": {"n": 1, "c": 2}})
    with pytest.raises(ValueError, match=message):
        prepare_input(source, tmp_path / "prepared", digest, termini)  # type: ignore[arg-type]
    assert not (tmp_path / "prepared").exists()


def test_rejects_invalid_termini_schema_and_unsupported_records(tmp_path: Path) -> None:
    source = _source(tmp_path)
    with pytest.raises(ValueError, match="exactly integer n and c"):
        prepare_input(source, tmp_path / "bad-schema", _digest(source), {"A": {"n": 1}})

    unsupported = tmp_path / "unsupported.pdb"
    unsupported.write_text("MODEL        1\nEND\n")
    with pytest.raises(ValueError, match="Unsupported PDB record"):
        prepare_input(
            unsupported,
            tmp_path / "unsupported-out",
            _digest(unsupported),
            {"A": {"n": 1, "c": 2}},
        )

    missing_end = tmp_path / "missing-end.pdb"
    missing_end.write_text(
        "".join(
            line
            for line in source.read_text().splitlines(keepends=True)
            if line != "END\n"
        )
    )
    with pytest.raises(ValueError, match="missing its END"):
        prepare_input(
            missing_end,
            tmp_path / "missing-end-out",
            _digest(missing_end),
            {"A": {"n": 1, "c": 2}},
        )


def test_rejects_reused_chain_segments(tmp_path: Path) -> None:
    lines = [
        _atom_line(1, "N", "ALA", "A", 1, (1.0, 2.0, 3.0), "N"),
        "TER\n",
        _atom_line(2, "N", "ALA", "B", 1, (4.0, 5.0, 6.0), "N"),
        "TER\n",
        _atom_line(3, "N", "ALA", "A", 2, (7.0, 8.0, 9.0), "N"),
        "END\n",
    ]
    source = tmp_path / "reused-chain.pdb"
    source.write_text("".join(lines))
    with pytest.raises(ValueError, match="occurs in multiple segments"):
        prepare_input(
            source,
            tmp_path / "reused-chain-out",
            _digest(source),
            {"A": {"n": 1, "c": 2}, "B": {"n": 1, "c": 1}},
        )


def test_rejects_altloc_duplicate_and_overwrite(tmp_path: Path) -> None:
    alt_dir = tmp_path / "alt"
    alt_dir.mkdir()
    alt_source = _source(alt_dir, altloc="A")
    with pytest.raises(ValueError, match="Alternate location"):
        prepare_input(
            alt_source,
            tmp_path / "alt-out",
            _digest(alt_source),
            {"A": {"n": 1, "c": 2}},
        )

    duplicate_dir = tmp_path / "duplicate"
    duplicate_dir.mkdir()
    duplicate_source = _source(duplicate_dir, duplicate=True)
    with pytest.raises(ValueError, match="Duplicate atom identity"):
        prepare_input(
            duplicate_source,
            tmp_path / "duplicate-out",
            _digest(duplicate_source),
            {"A": {"n": 1, "c": 2}},
        )

    good_dir = tmp_path / "good"
    good_dir.mkdir()
    good_source = _source(good_dir)
    output = tmp_path / "existing"
    output.mkdir()
    with pytest.raises(FileExistsError):
        prepare_input(
            good_source, output, _digest(good_source), {"A": {"n": 1, "c": 2}}
        )


def test_cli_reads_declared_termini_json(tmp_path: Path) -> None:
    source = _source(tmp_path)
    termini = tmp_path / "termini.json"
    termini.write_text(json.dumps({"A": {"n": 1, "c": 2}}))

    main(
        [
            "--source",
            str(source),
            "--source-sha256",
            _digest(source),
            "--termini",
            str(termini),
            "--output",
            str(tmp_path / "cli-output"),
        ]
    )

    assert (tmp_path / "cli-output/protein.pdb").exists()
