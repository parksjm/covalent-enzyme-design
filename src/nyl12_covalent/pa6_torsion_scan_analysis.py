"""Parse and compare bidirectional Gaussian relaxed torsion scans."""

from __future__ import annotations

import csv
import hashlib
import json
import logging
from pathlib import Path
from typing import Any

import numpy as np

from nyl12_covalent.pa6_gaussian_scan_parser import parse_scan_log
from nyl12_covalent.pa6_torsion_scan_matching import match_profile_overlap
from nyl12_covalent.pa6_torsion_scan_plot import (
    unwrap_angles_degrees,
    write_profile_plot,
)

LOGGER = logging.getLogger(__name__)
HARTREE_TO_KCAL_MOL = 627.509474


def analyze_manifest(manifest_path: Path, output_dir: Path) -> dict[str, Any]:
    """Analyze every completed forward/reverse scan in a manifest.

    Args:
        manifest_path: Scan manifest generated by the scan preparation tool.
        output_dir: New directory for CSV, JSON, and per-scan plots.

    Returns:
        Combined analysis report with profile and hysteresis data.

    Raises:
        FileExistsError: If the output directory already exists.
        ValueError: If the manifest or any required scan output is invalid.
        RuntimeError: If ImageMagick's ``convert`` executable is unavailable or
            cannot create a PNG profile plot.
    """
    if output_dir.exists():
        raise FileExistsError(f"Analysis output directory exists: {output_dir}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    records = manifest.get("scans")
    if not isinstance(records, list) or not records:
        raise ValueError("Scan manifest has no scan records")
    output_dir.mkdir(parents=True)
    analyses = []
    all_rows = []
    for record in records:
        analyses.append(_analyze_one_scan(manifest_path, record, output_dir, all_rows))
    report = {
        "schema_version": 1,
        "source_manifest": str(manifest_path.resolve()),
        "source_manifest_sha256": _sha256(manifest_path),
        "energy_reference": "minimum electronic energy across both directions",
        "energy_units": "kcal/mol relative to common profile minimum",
        "angular_matching": "minimum circular distance; unique greedy pairing; tolerance half the nominal scan increment",
        "scans": analyses,
    }
    (output_dir / "analysis.json").write_text(json.dumps(report, indent=2) + "\n")
    csv_path = output_dir / "scan_points.csv"
    with csv_path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(
            stream,
            fieldnames=[
                "fragment",
                "label",
                "direction",
                "point",
                "angle_degrees",
                "energy_hartree",
                "relative_energy_kcal_mol",
            ],
        )
        writer.writeheader()
        writer.writerows(all_rows)
    LOGGER.info("Analyzed %d bidirectional PA6 scans", len(analyses))
    return report


def _analyze_one_scan(
    manifest_path: Path,
    record: dict[str, Any],
    output_dir: Path,
    all_rows: list[dict[str, Any]],
) -> dict[str, Any]:
    label = str(record["label"])
    fragment = str(record["fragment"])
    increments = int(record["steps_per_direction"])
    expected_points = increments + 1
    indices = [int(value) for value in record["atom_indices_gaussian_one_based"]]
    paths = {
        direction: Path(record["directions"][direction]["input"]).parent / "scan.log"
        for direction in ("forward", "reverse")
    }
    profiles = {
        direction: parse_scan_log(path, indices, expected_points)
        for direction, path in paths.items()
    }
    common_minimum = min(
        point.energy_hartree for points in profiles.values() for point in points
    )
    relative = {
        direction: [
            (point.energy_hartree - common_minimum) * HARTREE_TO_KCAL_MOL
            for point in points
        ]
        for direction, points in profiles.items()
    }
    increment = abs(float(record["directions"]["forward"]["increment_degrees"]))
    tolerance = increment / 2.0
    matches = match_profile_overlap(
        [(point.index, point.angle_degrees) for point in profiles["forward"]],
        [(point.index, point.angle_degrees) for point in profiles["reverse"]],
        relative["forward"],
        relative["reverse"],
        tolerance,
    )
    coordinate_kind = str(record["coordinate_kind"])
    if coordinate_kind not in {"proper", "improper"}:
        raise ValueError(f"Unknown coordinate kind: {coordinate_kind}")
    scan_dir = output_dir / fragment / label
    scan_dir.mkdir(parents=True)
    for direction, points in profiles.items():
        for point, energy in zip(points, relative[direction], strict=True):
            all_rows.append(
                {
                    "fragment": fragment,
                    "label": label,
                    "direction": direction,
                    "point": point.index,
                    "angle_degrees": point.angle_degrees,
                    "energy_hartree": point.energy_hartree,
                    "relative_energy_kcal_mol": energy,
                }
            )
    write_profile_plot(
        scan_dir,
        label,
        {
            direction: [point.angle_degrees for point in points]
            for direction, points in profiles.items()
        },
        relative,
    )
    deltas = [match["hysteresis_kcal_mol"] for match in matches]
    if coordinate_kind == "improper":
        comparison_interpretation = (
            "Positive and negative scans are complementary branches from a "
            "reference minimum; energy differences summarize matched-angle "
            "overlap only, not a complete hysteresis cycle."
        )
    else:
        comparison_interpretation = (
            "Energy hysteresis summarizes matched-angle overlap only; "
            "unmatched portions of the scan branches are not compared."
        )
    return {
        "fragment": fragment,
        "label": label,
        "coordinate_kind": coordinate_kind,
        "modredundant_increments_per_direction": increments,
        "expected_points_per_direction": expected_points,
        "forward_log": str(paths["forward"].resolve()),
        "reverse_log": str(paths["reverse"].resolve()),
        "forward_log_sha256": _sha256(paths["forward"]),
        "reverse_log_sha256": _sha256(paths["reverse"]),
        "common_minimum_hartree": common_minimum,
        "matched_overlap_count": len(matches),
        "unmatched_forward_count": expected_points - len(matches),
        "unmatched_reverse_count": expected_points - len(matches),
        "angular_matching_tolerance_degrees": tolerance,
        "comparison_interpretation": comparison_interpretation,
        "matched_overlap_mean_abs_energy_difference_kcal_mol": (
            float(np.mean(np.abs(deltas))) if deltas else None
        ),
        "matched_overlap_max_abs_energy_difference_kcal_mol": (
            float(np.max(np.abs(deltas))) if deltas else None
        ),
        "matched_points": matches,
        "raw_signed_profiles": {
            direction: [
                {
                    "point": point.index,
                    "angle_degrees": point.angle_degrees,
                    "energy_hartree": point.energy_hartree,
                    "relative_energy_kcal_mol": energy,
                    "plot_angle_unwrapped_degrees": unwrapped,
                }
                for point, energy, unwrapped in zip(
                    profiles[direction],
                    relative[direction],
                    unwrap_angles_degrees(
                        [point.angle_degrees for point in profiles[direction]]
                    ),
                    strict=True,
                )
            ]
            for direction in profiles
        },
        "plot_png": str((scan_dir / "energy_profile.png").resolve()),
        "plot_svg": str((scan_dir / "energy_profile.svg").resolve()),
        "scan_manifest": str(manifest_path.resolve()),
    }


def _sha256(path: Path) -> str:
    """Return the SHA-256 digest for one retained analysis input."""
    return hashlib.sha256(path.read_bytes()).hexdigest()
