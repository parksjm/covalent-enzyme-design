"""Import a verified source snapshot into a new or empty checkout."""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import tarfile
from pathlib import Path, PurePosixPath


def import_snapshot(archive: Path, inventory: Path, destination: Path) -> None:
    """Verify all archive bytes before importing and record the exact procedure.

    Args:
        archive: Tarball generated by inventory_covalent_pipeline.py.
        inventory: Matching file inventory.
        destination: New or empty standalone checkout directory.
    """
    destination = destination.absolute()
    if destination.exists() and any(destination.iterdir()):
        raise FileExistsError(f"Destination must be empty: {destination}")
    report = json.loads(inventory.read_text())
    expected = {row["path"]: row for row in report["files"]}
    verified: dict[str, bytes] = {}
    with tarfile.open(archive, "r:gz") as source:
        members = source.getmembers()
        if len(members) != len(expected) or {m.name for m in members} != set(expected):
            raise ValueError("Archive and inventory file lists differ")
        for member in members:
            name = PurePosixPath(member.name)
            if name.is_absolute() or ".." in name.parts or not member.isfile():
                raise ValueError(f"Unsafe archive member: {member.name}")
            stream = source.extractfile(member)
            if stream is None:
                raise ValueError(f"Missing archive bytes: {member.name}")
            with stream:
                data = stream.read()
            row = expected[member.name]
            if len(data) != row["size_bytes"] or hashlib.sha256(data).hexdigest() != row["sha256"]:
                raise ValueError(f"Snapshot digest mismatch: {member.name}")
            verified[member.name] = data
    destination.mkdir(parents=True, exist_ok=True)
    for name, data in verified.items():
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True)
        with target.open("xb") as stream:
            stream.write(data)
    template = destination / "tools/covalent_repository_template"
    for name in ("README.md", "AGENTS.md", "pyproject.toml", ".gitignore"):
        shutil.copyfile(template / name, destination / name)
    provenance = destination / "provenance"
    provenance.mkdir()
    shutil.copyfile(inventory, provenance / "source_inventory.json")
    shutil.copyfile(__file__, provenance / "import_snapshot.py")
    (provenance / "import.json").write_text(json.dumps({
        "archive_source": str(archive.resolve()),
        "archive_sha256": hashlib.sha256(archive.read_bytes()).hexdigest(),
        "inventory_sha256": hashlib.sha256(inventory.read_bytes()).hexdigest(),
        "source_file_count": len(verified),
        "root_files_copied_from": "tools/covalent_repository_template",
        "argv": ["import_snapshot.py", str(archive), str(inventory), str(destination)],
    }, indent=2) + "\n")


def main() -> None:
    """Parse and import the explicit archive, inventory, and destination."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("inventory", type=Path)
    parser.add_argument("destination", type=Path)
    args = parser.parse_args()
    import_snapshot(args.archive, args.inventory, args.destination)


if __name__ == "__main__":
    main()
